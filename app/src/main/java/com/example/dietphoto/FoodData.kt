fun String.toFoodDisplayName(): String {
    val normalized = this.lowercase().replace(' ', '_').replace('-', '_')
    return FOOD101_POLISH_NAMES[normalized]
        ?: this.replace('_', ' ').split(' ')
            .joinToString(" ") { it.replaceFirstChar { c -> c.uppercaseChar() } }
}

fun nutritionFor(label: String): NutritionPer100g {
    val normalized = label.lowercase().replace(' ', '_').replace('-', '_')
    return FOOD101_NUTRITION[normalized]
        ?: FOOD101_NUTRITION.entries
            .firstOrNull { normalized.contains(it.key) || it.key.contains(normalized) }
            ?.value
        ?: NutritionPer100g(200, 10.0f, 8.0f, 20.0f, 1.0f, 0.50f)
}
